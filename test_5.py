# Описание раздела документации "Просмотр трассировки (Trace Viewer)" своими словами:
# Playwright Trace Viewer — это графический инструмент (GUI), который позволяет после завершения теста
# пошагово (вперед и назад во времени) просмотреть каждое выполненное действие.
#
# 1. Запись трассировки через Pytest:
#    Для включения записи используется флаг `--tracing`:
#    Команда: `pytest --tracing on`
#
# 2. Режимы работы флага `--tracing`:
#    - `off` — трассировка отключена (значение по умолчанию).
#    - `on` — записывать трассировку абсолютно для каждого теста.
#    - `retain-on-failure` — записывать трассировку для всех тестов, но автоматически удалять её,
#      если тест прошел успешно (файлы сохраняются только для упавших с ошибкой тестов, чтобы не забивать диск).
#
# 3. Куда сохраняется результат:
#    Playwright автоматически создает папку `test-results`, внутри которой создает подпапку с именем теста
#    и кладет туда архив `trace.zip`.
#
# 4. Как открыть записанную трассировку:
#    Команда: `playwright show-trace trace.zip` (нужно указать полный путь к файлу в папке test-results)
#    или загрузить архив в веб-версию на сайте trace.playwright.dev.
#    Особенность Trace Viewer в том, что он делает не просто видео, а полный снимок DOM-дерева (DOM snapshot)
#    до и после каждого клика: в окне просмотра можно открывать DevTools, искать локаторы, читать сетевые
#    запросы (Network) и видеть подсвеченную строчку исходного кода на каждом шаге.

import re
from playwright.sync_api import Page, expect


def test_get_started_trace(page: Page):
    page.goto("https://playwright.dev/")
    page.get_by_role("link", name="Get started").click()
    expect(page.get_by_role("heading", name="Installation")).to_be_visible()
